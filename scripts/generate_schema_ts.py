"""Generate frontend/src/schema.ts from the pydantic models in neurolume.schema.

Run this after every schema change:

    python scripts/generate_schema_ts.py

The converter only understands the JSON Schema features our models use, which
keeps it short enough to read in one sitting.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "python"))

from neurolume.schema import SCHEMA_VERSION, Graph  # noqa: E402

OUTPUT = ROOT / "frontend" / "src" / "schema.ts"


def ts_type(schema: dict[str, Any]) -> str:
    """Translate one JSON Schema fragment into a TypeScript type expression."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(f'"{value}"' for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(option) for option in schema["anyOf"])
    if "prefixItems" in schema:
        return "[" + ", ".join(ts_type(item) for item in schema["prefixItems"]) + "]"

    kind = schema.get("type")
    if kind == "array":
        item = ts_type(schema["items"])
        return f"({item})[]" if "|" in item else f"{item}[]"
    if kind == "object":
        extra = schema.get("additionalProperties")
        value = ts_type(extra) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}[kind]


def ts_interface(name: str, schema: dict[str, Any]) -> str:
    lines = []
    if "description" in schema:
        lines.append("/** " + " ".join(schema["description"].split()) + " */")
    lines.append(f"export interface {name} {{")
    # Python always serialises every field (defaults included), so all are required here.
    for field, field_schema in schema["properties"].items():
        lines.append(f"  {field}: {ts_type(field_schema)};")
    lines.append("}")
    return "\n".join(lines)


def generate() -> str:
    schema = Graph.model_json_schema(mode="serialization")
    definitions = dict(schema.pop("$defs"))
    definitions["Graph"] = schema

    node_type = definitions["GraphNode"]["properties"]["type"]
    parts = [
        "// Generated by scripts/generate_schema_ts.py from python/neurolume/schema.py.",
        "// Do not edit by hand; change the pydantic models and re-run the script.",
        "",
        f'export const SCHEMA_VERSION = "{SCHEMA_VERSION}";',
        "",
        f"export type NodeType = {ts_type(node_type)};",
    ]
    for name in sorted(definitions):
        parts += ["", ts_interface(name, definitions[name])]
    text = "\n".join(parts) + "\n"
    return text.replace(f": {ts_type(node_type)};", ": NodeType;")


if __name__ == "__main__":
    OUTPUT.write_text(generate(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
